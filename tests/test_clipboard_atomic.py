def test_native_owner_accepts_legal_null_and_clears_stale_last_error():
    native=NativeClipboard.__new__(NativeClipboard)
    native.user=SimpleNamespace(GetClipboardOwner=lambda:None)
    native.api=SimpleNamespace(GetClipboardOwner=lambda:pytest.fail('pywin32 null-owner wrapper must not be used'))
    ctypes.set_last_error(5)
    assert native.owner()==0 and ctypes.get_last_error()==0


def test_native_owner_retains_real_owner_and_rejects_actual_access_error():
    native=NativeClipboard.__new__(NativeClipboard)
    native.user=SimpleNamespace(GetClipboardOwner=lambda:777)
    assert native.owner()==777
    def failed():ctypes.set_last_error(5);return None
    native.user.GetClipboardOwner=failed
    with pytest.raises(RuntimeError,match='owner could not be verified'):native.owner()


