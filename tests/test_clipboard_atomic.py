"""Concurrent writers exercise clipboard lock/CAS semantics on private fixtures.

No test opens, inspects, or changes the user's Windows clipboard. Every clipboard
revision is generated by writes, not a mock returning a fixed sequence number.
"""
from contextlib import contextmanager
import threading
import pytest
from murmur import windows
from murmur.clipboard import decode_unicode, NativeClipboard
import ctypes
from types import SimpleNamespace


def unicode(text):return text.encode('utf-16-le')+b'\0\0'


class ClipboardFixture:
    MAX_BYTES=8*1024*1024
    TEXT_FORMATS=frozenset((1,7,13,16));UNICODE=13
    def __init__(self):
        self.lock=threading.Lock();self.lock_thread=None;self.open_owner=0
        self.values={1:b'original ANSI \x80\0',7:b'original OEM \x82\0',13:unicode('Original clipboard'),16:b'\x09\x04\0\0'}
        self.revision=1;self.actual_owner=900;self.pid_by_owner={900:90,777:70,1200:12,1300:13,1400:14}
        self.on_formats=None;self.on_replace=None;self.on_sequence=None;self.closed=threading.Event()
        self.mutations=0;self.fail_prepare=False;self.fail_next_replace=False;self.allocated=[]
    def _locked(self):assert self.lock_thread==threading.get_ident(), 'Clipboard read or write outside OpenClipboard'
    @contextmanager
    def opened(self,owner):
        if not self.lock.acquire(blocking=False):raise windows.ClipboardBusy('Synthetic clipboard lock contention')
        self.lock_thread=threading.get_ident();self.open_owner=owner;self.closed.clear()
        try:yield self
        finally:self.lock_thread=None;self.lock.release();self.closed.set()
    def sequence(self):
        self._locked()
        if self.on_sequence:callback=self.on_sequence;self.on_sequence=None;callback()
        return self.revision
    def owner(self):self._locked();return self.actual_owner
    def owner_pid(self,owner):self._locked();return self.pid_by_owner.get(owner,0)
    def formats(self):
        self._locked()
        if self.on_formats:callback=self.on_formats;self.on_formats=None;callback()
        return list(self.values)
    def data(self,format):self._locked();return bytes(self.values[format])
    def prepare(self,values):
        if self.fail_prepare:raise RuntimeError('Synthetic private allocation failure')
        result=[[format,bytes(data)] for format,data in values];self.allocated.extend(result);return result
    def replace(self,prepared):
        self._locked();self.values={};self.actual_owner=self.open_owner;self.revision+=1;self.mutations+=1
        for entry in prepared:
            self.values[entry[0]]=entry[1];entry[1]=None;self.revision+=1
            if self.on_replace:callback=self.on_replace;self.on_replace=None;callback()
            if self.fail_next_replace:self.fail_next_replace=False;raise RuntimeError('Synthetic SetClipboardData failure')
    def release(self,prepared):
        for entry in prepared:entry[1]=None
    def external_copy(self,text,owner=1400,delayed=False):
        if not self.lock.acquire(blocking=False):return False
        try:
            self.values={13:unicode(text)};self.actual_owner=owner
            if not delayed:self.revision+=2
            return True
        finally:self.lock.release()
    def text(self):return decode_unicode(self.values[13])


@pytest.fixture
def clipboard(monkeypatch):
    clipboard=ClipboardFixture()
    monkeypatch.setattr(windows,'_clipboard_backend',lambda:clipboard)
    monkeypatch.setattr(windows,'_clipboard_owner',lambda:777)
    # Any fallback to a Qt clipboard API would reopen the TOCTOU gap.
    monkeypatch.setattr(windows.QApplication,'clipboard',lambda:pytest.fail('Qt clipboard API must not be used'))
    return clipboard


def competing_writer(clipboard,text):
    """A second thread attempts a copy exactly inside a guarded transaction."""
    first_attempt=threading.Event();finished=threading.Event();attempts=[]
    def writer():
        attempts.append(clipboard.external_copy(text));first_attempt.set()
        assert clipboard.closed.wait(2)
        attempts.append(clipboard.external_copy(text));finished.set()
    def checkpoint():
        worker.start();assert first_attempt.wait(2)
        assert attempts==[False]  # OpenClipboard actively excluded the writer.
    worker=threading.Thread(target=writer)
    return checkpoint,worker,finished,attempts


def test_snapshot_cannot_mix_old_formats_with_concurrent_new_text(clipboard):
    original=dict(clipboard.values)
    checkpoint,writer,done,attempts=competing_writer(clipboard,'New copy during snapshot')
    clipboard.on_formats=checkpoint
    tx=windows.ClipboardTransaction();assert done.wait(2);writer.join(2)
    assert attempts==[False,True] and dict(tx.saved)==original
    assert clipboard.text()=='New copy during snapshot'
    before=clipboard.mutations
    with pytest.raises(RuntimeError,match='clipboard changed'):tx.write('Dictation result')
    assert clipboard.text()=='New copy during snapshot' and clipboard.mutations==before and tx.finished


def test_write_revision_cannot_be_stolen_by_copy_between_set_and_sequence(clipboard):
    tx=windows.ClipboardTransaction()
    checkpoint,writer,done,attempts=competing_writer(clipboard,'New copy just after write')
    clipboard.on_replace=checkpoint;tx.write('Dictation result')
    assert done.wait(2);writer.join(2)
    assert attempts==[False,True] and tx.sequence<clipboard.revision
    assert not tx.restore() and clipboard.text()=='New copy just after write'


def test_restore_comparison_and_replacement_exclude_concurrent_writer(clipboard):
    tx=windows.ClipboardTransaction();tx.write('Dictation result')
    checkpoint,writer,done,attempts=competing_writer(clipboard,'New copy during restoration')
    clipboard.on_sequence=checkpoint
    assert tx.restore();assert done.wait(2);writer.join(2)
    assert attempts==[False,True] and clipboard.text()=='New copy during restoration'
    assert not tx.restore()  # Does not retry after the user copied again.


