@pytest.mark.parametrize('copy_again',[False,True])
def test_restore_busy_changes_no_state_and_retry_always_rechecks_cas(clipboard,copy_again):
    original=dict(clipboard.values);tx=windows.ClipboardTransaction();tx.write('Temporary text')
    assert clipboard.lock.acquire(blocking=False)
    try:
        with pytest.raises(windows.ClipboardBusy):tx.restore()
    finally:clipboard.lock.release()
    assert not tx.finished and not tx.restored and clipboard.text()=='Temporary text'
    if copy_again:
        assert clipboard.external_copy('Copied while restore was busy')
        assert not tx.restore() and clipboard.text()=='Copied while restore was busy'
    else:
        assert tx.restore() and clipboard.values==original
    assert tx.finished


def test_initial_snapshot_and_write_busy_never_mutate_existing_clipboard(clipboard):
    original=dict(clipboard.values);clipboard.lock.acquire()
    try:
        with pytest.raises(windows.ClipboardBusy):windows.ClipboardTransaction()
    finally:clipboard.lock.release()
    tx=windows.ClipboardTransaction();clipboard.lock.acquire()
    try:
        with pytest.raises(windows.ClipboardBusy):tx.write('Result')
    finally:clipboard.lock.release()
    assert clipboard.values==original and not clipboard.mutations and tx.finished


